-- 6a. Recompute virtual B2B bundle capacity (PRD-004 = 10 PRD-001 + 8 PRD-002 + 7 PRD-005)
create or replace function public.sync_bundle_stock(p_bundle_id text default 'PRD-004')
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_brokoli integer;
  v_tomat integer;
  v_wortel integer;
  v_capacity integer;
begin
  select stock_kg into v_brokoli from public.products where id = 'PRD-001';
  select stock_kg into v_tomat   from public.products where id = 'PRD-002';
  select stock_kg into v_wortel  from public.products where id = 'PRD-005';

  if v_brokoli is null or v_tomat is null or v_wortel is null then
    v_capacity := 0;
  else
    v_capacity := greatest(0, least(v_brokoli / 10, v_tomat / 8, v_wortel / 7));
  end if;

  update public.products
  set stock_kg = v_capacity
  where id = p_bundle_id;

  return v_capacity;
end;
$$;

-- 6b. Atomic manual stock adjustment with inventory ledger + bundle resync
create or replace function public.adjust_product_stock(
  p_product_id text,
  p_new_stock integer,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_before integer;
  v_bundle integer;
begin
  if p_product_id = 'PRD-004' then
    raise exception 'BUNDLE_READONLY: Stok Paket B2B dihitung otomatis dari stok komoditas segar dan tidak bisa diubah manual';
  end if;
  if p_new_stock is null or p_new_stock < 0 then
    raise exception 'INVALID_STOCK: stockKg tidak boleh negatif';
  end if;

  select stock_kg into v_before
  from public.products
  where id = p_product_id
  for update;

  if not found then
    raise exception 'PRODUCT_NOT_FOUND: Komoditas % tidak ditemukan', p_product_id;
  end if;

  update public.products
  set stock_kg = p_new_stock
  where id = p_product_id;

  if p_new_stock <> v_before then
    insert into public.stock_movements (product_id, delta, stock_before, stock_after, reason, note)
    values (p_product_id, p_new_stock - v_before, v_before, p_new_stock, 'MANUAL_ADJUSTMENT', p_note);
  end if;

  v_bundle := public.sync_bundle_stock('PRD-004');

  return jsonb_build_object(
    'id', p_product_id,
    'stockBefore', v_before,
    'stockKg', p_new_stock,
    'bundleCapacity', v_bundle
  );
end;
$$;

-- 6c. Atomic checkout: lock stock -> validate -> deduct -> ledger -> order -> sales_history -> bundle resync
create or replace function public.checkout_order(
  p_order_id text,
  p_buyer_mode text,
  p_courier text,
  p_qr_code_resi text,
  p_payment_method text,
  p_shipping_fee bigint,
  p_cart jsonb,
  p_recorded_date date,
  p_is_weekend boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item record;
  v_prod public.products%rowtype;
  v_price bigint;
  v_subtotal bigint := 0;
  v_order_items jsonb := '[]'::jsonb;
  v_ded record;
  v_total bigint;
  v_bundle integer;
begin
  if p_buyer_mode not in ('B2C', 'B2B') then
    raise exception 'INVALID_BUYER_MODE: buyerMode harus B2C atau B2B';
  end if;

  if p_cart is null or jsonb_typeof(p_cart) <> 'array' or jsonb_array_length(p_cart) = 0 then
    raise exception 'EMPTY_CART: cart tidak boleh kosong';
  end if;

  -- Aggregate requested cart items
  create temporary table if not exists _vc_req (
    product_id text primary key,
    qty integer not null
  ) on commit drop;
  truncate _vc_req;

  insert into _vc_req (product_id, qty)
  select
    (elem->>'productId')::text,
    sum((elem->>'qty')::integer)
  from jsonb_array_elements(p_cart) as elem
  group by (elem->>'productId')::text;

  if exists (select 1 from _vc_req where product_id is null or product_id = '' or qty <= 0) then
    raise exception 'INVALID_CART_ITEM: Setiap item cart wajib punya productId dan qty >= 1';
  end if;

  -- Expand PRD-004 virtual bundle into fresh component deductions
  create temporary table if not exists _vc_ded (
    product_id text primary key,
    qty integer not null
  ) on commit drop;
  truncate _vc_ded;

  insert into _vc_ded (product_id, qty)
  select product_id, sum(qty)::integer
  from (
    select product_id, qty from _vc_req where product_id <> 'PRD-004'
    union all
    select comp.id, r.qty * comp.per_krat
    from _vc_req r
    cross join (values ('PRD-001', 10), ('PRD-002', 8), ('PRD-005', 7)) as comp(id, per_krat)
    where r.product_id = 'PRD-004'
  ) expanded
  group by product_id;

  -- Validate requested products & compute order items + subtotal
  for v_item in select product_id, qty from _vc_req order by product_id loop
    select * into v_prod from public.products where id = v_item.product_id;
    if not found then
      raise exception 'PRODUCT_NOT_FOUND: Produk % tidak ditemukan', v_item.product_id;
    end if;
    v_price := case when p_buyer_mode = 'B2B' then v_prod.price_b2b else v_prod.price_b2c end;
    v_subtotal := v_subtotal + (v_price * v_item.qty);
    v_order_items := v_order_items || jsonb_build_array(
      jsonb_build_object(
        'productId', v_prod.id,
        'name', v_prod.name,
        'qty', v_item.qty,
        'price', v_price,
        'unit', v_prod.unit
      )
    );
  end loop;

  -- Lock deducted products in deterministic order to avoid deadlocks
  for v_ded in select product_id, qty from _vc_ded order by product_id loop
    select * into v_prod from public.products where id = v_ded.product_id for update;
    if not found then
      raise exception 'COMPONENT_NOT_FOUND: Komponen % tidak ditemukan di gudang', v_ded.product_id;
    end if;
    if v_prod.stock_kg < v_ded.qty then
      raise exception 'INSUFFICIENT_STOCK: Stok % tidak cukup (tersedia %, diminta %)',
        v_prod.name, v_prod.stock_kg, v_ded.qty;
    end if;

    update public.products
    set stock_kg = v_prod.stock_kg - v_ded.qty
    where id = v_prod.id;

    insert into public.stock_movements (product_id, delta, stock_before, stock_after, reason, reference_id)
    values (v_prod.id, -v_ded.qty, v_prod.stock_kg, v_prod.stock_kg - v_ded.qty, 'ORDER_CHECKOUT', p_order_id);
  end loop;

  v_total := v_subtotal + p_shipping_fee;

  insert into public.orders (
    id, date_label, buyer_mode, status, status_label, courier, qr_code_resi,
    payment_method, items, shipping_fee, total_amount, pod_signed, pod_timestamp
  ) values (
    p_order_id,
    'Baru saja',
    p_buyer_mode,
    'PACKING_QR',
    'Pembayaran Terverifikasi • Packing & Label QR',
    p_courier,
    p_qr_code_resi,
    p_payment_method,
    v_order_items,
    p_shipping_fee,
    v_total,
    false,
    null
  );

  -- Record actual commodity demand (with PRD-004 expanded to component kg) into sales_history
  for v_ded in select product_id, qty from _vc_ded order by product_id loop
    insert into public.sales_history (
      recorded_date, commodity_id, sold_b2c_kg, sold_b2b_kg, total_demand_kg, weather_condition, is_weekend
    ) values (
      p_recorded_date,
      v_ded.product_id,
      case when p_buyer_mode = 'B2C' then v_ded.qty else 0 end,
      case when p_buyer_mode = 'B2B' then v_ded.qty else 0 end,
      v_ded.qty,
      'cerah',
      p_is_weekend
    )
    on conflict (commodity_id, recorded_date) do update set
      sold_b2c_kg = public.sales_history.sold_b2c_kg + excluded.sold_b2c_kg,
      sold_b2b_kg = public.sales_history.sold_b2b_kg + excluded.sold_b2b_kg,
      total_demand_kg = round((public.sales_history.sold_b2c_kg + excluded.sold_b2c_kg + public.sales_history.sold_b2b_kg + excluded.sold_b2b_kg)::numeric, 2),
      is_weekend = excluded.is_weekend,
      updated_at = now();
  end loop;

  v_bundle := public.sync_bundle_stock('PRD-004');

  return jsonb_build_object(
    'orderId', p_order_id,
    'totalAmount', v_total,
    'bundleCapacity', v_bundle
  );
end;
$$;

-- 6d. Atomic Purchase Order issuance (locks supply plan + enforces 1 PO per plan)
create or replace function public.issue_purchase_order(
  p_plan_id text,
  p_po_number text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plan public.supply_plans%rowtype;
  v_existing_po text;
  v_total bigint;
begin
  select * into v_plan
  from public.supply_plans
  where id = p_plan_id
  for update;

  if not found then
    raise exception 'PLAN_NOT_FOUND: Rencana pasokan % tidak ditemukan', p_plan_id;
  end if;

  select po_number into v_existing_po
  from public.purchase_orders
  where plan_id = p_plan_id;

  if v_existing_po is not null then
    raise exception 'PO_ALREADY_EXISTS: PO % sudah diterbitkan untuk rencana %', v_existing_po, p_plan_id;
  end if;

  if v_plan.status = 'WAITING_FARMER' then
    raise exception 'PLAN_NOT_CONFIRMED: Petani belum mengonfirmasi volume & harga untuk rencana ini';
  end if;

  if v_plan.status <> 'CONFIRMED_BY_FARMER' then
    raise exception 'INVALID_PLAN_STATUS: Rencana berstatus %; PO hanya bisa diterbitkan setelah konfirmasi petani', v_plan.status;
  end if;

  if v_plan.confirmed_qty <= 0 then
    raise exception 'INVALID_QTY: Jumlah yang disepakati petani tidak valid';
  end if;

  v_total := v_plan.confirmed_qty::bigint * v_plan.agreed_price::bigint;

  insert into public.purchase_orders (
    po_number, plan_id, commodity_id, commodity_name, qty, agreed_price, total_amount, status
  ) values (
    p_po_number,
    v_plan.id,
    v_plan.commodity_id,
    v_plan.commodity_name,
    v_plan.confirmed_qty,
    v_plan.agreed_price,
    v_total,
    'PO_ISSUED'
  );

  update public.supply_plans
  set status = 'PO_ISSUED'
  where id = p_plan_id;

  return jsonb_build_object(
    'poNumber', p_po_number,
    'planId', p_plan_id,
    'totalAmount', v_total
  );
end;
$$;

-- 6e. Atomic QC Grading: lock PO + products -> increment Grade-A & Grade-B -> ledger -> audit -> bundle resync
create or replace function public.complete_qc_grading(
  p_po_number text,
  p_grade_a_kg integer,
  p_grade_b_kg integer,
  p_pouches_per_kg integer default 2,
  p_processed_product_id text default 'PRD-003'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_po public.purchase_orders%rowtype;
  v_fresh_before integer;
  v_proc_before integer;
  v_grade_b_pouches integer;
  v_bundle integer;
begin
  if p_grade_a_kg is null or p_grade_b_kg is null or p_grade_a_kg < 0 or p_grade_b_kg < 0 then
    raise exception 'INVALID_GRADE: gradeAKg dan gradeBKg tidak boleh negatif';
  end if;

  select * into v_po
  from public.purchase_orders
  where po_number = p_po_number
  for update;

  if not found then
    raise exception 'PO_NOT_FOUND: PO % tidak ditemukan', p_po_number;
  end if;

  if v_po.status = 'QC_COMPLETED' then
    raise exception 'PO_ALREADY_QC: PO % sudah selesai QC', p_po_number;
  end if;

  if v_po.status <> 'HARVEST_SENT_TO_QC' then
    raise exception 'INVALID_PO_STATUS: PO % berstatus %; kirim hasil panen ke QC terlebih dahulu', p_po_number, v_po.status;
  end if;

  if (p_grade_a_kg + p_grade_b_kg) <> v_po.qty then
    raise exception 'GRADE_SUM_MISMATCH: Total Grade-A + Grade-B (%) harus sama dengan qty PO (%)',
      (p_grade_a_kg + p_grade_b_kg), v_po.qty;
  end if;

  v_grade_b_pouches := p_grade_b_kg * greatest(1, p_pouches_per_kg);

  -- Lock products in deterministic order to avoid deadlocks
  if p_grade_b_kg > 0 and p_processed_product_id <> v_po.commodity_id then
    perform 1 from public.products
    where id in (v_po.commodity_id, p_processed_product_id)
    order by id
    for update;
  else
    perform 1 from public.products
    where id = v_po.commodity_id
    for update;
  end if;

  select stock_kg into v_fresh_before from public.products where id = v_po.commodity_id;
  if v_fresh_before is null then
    raise exception 'PRODUCT_NOT_FOUND: Komoditas % tidak ditemukan', v_po.commodity_id;
  end if;

  if p_grade_a_kg > 0 then
    update public.products
    set stock_kg = v_fresh_before + p_grade_a_kg
    where id = v_po.commodity_id;

    insert into public.stock_movements (product_id, delta, stock_before, stock_after, reason, reference_id)
    values (v_po.commodity_id, p_grade_a_kg, v_fresh_before, v_fresh_before + p_grade_a_kg, 'QC_GRADE_A', p_po_number);
  end if;

  if p_grade_b_kg > 0 then
    select stock_kg into v_proc_before from public.products where id = p_processed_product_id;
    if v_proc_before is null then
      raise exception 'PRODUCT_NOT_FOUND: Komoditas olahan % tidak ditemukan', p_processed_product_id;
    end if;

    update public.products
    set stock_kg = v_proc_before + v_grade_b_pouches
    where id = p_processed_product_id;

    insert into public.stock_movements (product_id, delta, stock_before, stock_after, reason, reference_id, note)
    values (
      p_processed_product_id,
      v_grade_b_pouches,
      v_proc_before,
      v_proc_before + v_grade_b_pouches,
      'QC_GRADE_B_PROCESSED',
      p_po_number,
      format('%s kg Grade-B dari %s diolah menjadi %s pouch', p_grade_b_kg, v_po.commodity_id, v_grade_b_pouches)
    );
  end if;

  update public.purchase_orders
  set
    status = 'QC_COMPLETED',
    grade_a_kg = p_grade_a_kg,
    grade_b_kg = p_grade_b_kg,
    grade_b_pouches = v_grade_b_pouches,
    qc_completed_at = now()
  where po_number = p_po_number;

  v_bundle := public.sync_bundle_stock('PRD-004');

  return jsonb_build_object(
    'poNumber', p_po_number,
    'gradeAKg', p_grade_a_kg,
    'gradeBKg', p_grade_b_kg,
    'gradeBPouches', v_grade_b_pouches,
    'processedProductId', p_processed_product_id,
    'bundleCapacity', v_bundle
  );
end;
$$;

